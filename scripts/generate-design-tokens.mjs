import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const manifestUrl = new URL('../design-system/tokens.json', import.meta.url);
const outputUrl = new URL('../design-system/tokens.css', import.meta.url);
const {tokens} = JSON.parse(await fs.readFile(manifestUrl, 'utf8'));
const names = tokens.map(token => token.name);
if (tokens.length !== 61 || new Set(names).size !== 61) throw new Error('Expected 61 unique reference tokens');
for (const token of tokens) {
  if (!/^[a-z][a-z0-9-]+$/.test(token.name) || /[;{}\n]/.test(token.light)) throw new Error(`Invalid token: ${token.name}`);
  if (token.assignmentStatus !== 'proposed') throw new Error(`Unreviewed status change: ${token.name}`);
}
const css = `/* Generated by scripts/generate-design-tokens.mjs. Do not edit by hand.
 * PROPOSED semantic mappings, implemented only in the local light catalog.
 * No :root rules, no dark overrides, no production screen consumers.
 * Literal provenance and unimplemented dark proposals: tokens.json.
 */
:where(.rancana-foundation) {
${tokens.map(token => `  --${token.name}: ${token.light};`).join('\n')}
}
`;
// Explicitly allow only exact-value production aliases; proposed recipes remain opt-in.
const webNames = ['brand-green', 'color-text', 'color-text-muted', 'color-border', 'color-bg', 'color-primary-hover', 'font-heading', 'font-body'];
const webCss = `/* Generated by scripts/generate-design-tokens.mjs; exact-value web aliases only. */
:root {
${webNames.map(name => `  --rancana-foundation-${name}: ${tokens.find(token => token.name === name).light};`).join('\n')}
}
`;
const webOutputUrl = new URL('../foundation-tokens.css', import.meta.url);
if (process.argv.includes('--check')) {
  if (await fs.readFile(webOutputUrl, 'utf8') !== webCss) throw new Error('foundation-tokens.css is stale');
  if (await fs.readFile(outputUrl, 'utf8') !== css) throw new Error('tokens.css is stale; run node scripts/generate-design-tokens.mjs');
  console.log('61 proposed reference tokens match the generated light CSS');
} else {
  await fs.writeFile(outputUrl, css);
  await fs.writeFile(webOutputUrl, webCss);
  console.log(`Generated ${fileURLToPath(outputUrl)}`);
}
